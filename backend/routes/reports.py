# Download Report PDF
@reports_bp.route("/download/<int:report_id>", methods=["GET"])
@jwt_required()
def download_report(report_id):

    try:

        user_id = get_jwt_identity()

        company = Company.query.filter_by(
            user_id=user_id
        ).first()

        if company is None:

            return jsonify({
                "success": False,
                "message": "Company not found"
            }), 404

        report = Report.query.filter_by(
            id=report_id,
            company_id=company.id
        ).first()

        if report is None:

            return jsonify({
                "success": False,
                "message": "Report not found"
            }), 404

        buffer = BytesIO()

        document = SimpleDocTemplate(buffer)

        styles = getSampleStyleSheet()

        story = []

        story.append(Paragraph("<b>EcoFinance SL</b>", styles["Title"]))

        story.append(Paragraph(
            "ESG Sustainability Report",
            styles["Heading1"]
        ))

        story.append(Spacer(1, 20))

        story.append(Paragraph(
            f"<b>Company:</b> {company.company_name}",
            styles["Normal"]
        ))

        story.append(Paragraph(
            f"<b>Report:</b> {report.report_title}",
            styles["Normal"]
        ))

        story.append(Paragraph(
            f"<b>Type:</b> {report.report_type}",
            styles["Normal"]
        ))

        story.append(Paragraph(
            f"<b>Date:</b> {report.generated_at.strftime('%Y-%m-%d %H:%M:%S')}",
            styles["Normal"]
        ))

        story.append(Spacer(1, 20))

        story.append(Paragraph(
            "<b>Report Details</b>",
            styles["Heading2"]
        ))

        story.append(Paragraph(
            report.report_content.replace("\n", "<br/>"),
            styles["BodyText"]
        ))

        document.build(story)

        buffer.seek(0)

        return send_file(

            buffer,

            as_attachment=True,
            download_name=f"Report_{report.id}.pdf",
            mimetype="application/pdf"

        )

    except Exception as e:

        return jsonify({

            "success": False,
            "message": str(e)

        }), 500